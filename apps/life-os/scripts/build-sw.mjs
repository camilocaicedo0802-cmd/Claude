// Generates out/sw.js after `next build`: a service worker that precaches every file of the
// static export, so LIFE OS opens instantly and works offline once it has been opened once.
// Each build gets a new version hash; the browser installs the new worker and drops the old cache.
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "out");

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const full = path.join(dir, name);
    return statSync(full).isDirectory() ? walk(full) : [full];
  });
}

const files = walk(root)
  .map((f) => path.relative(root, f).split(path.sep).join("/"))
  .filter((f) => f !== "sw.js" && !f.endsWith(".map") && !f.startsWith("404") && !f.startsWith("_not-found"))
  .sort();

const hash = createHash("sha256");
for (const f of files) hash.update(f).update(readFileSync(path.join(root, f)));
const version = hash.digest("hex").slice(0, 12);

const sw = `/* LIFE OS service worker · generated by scripts/build-sw.mjs · version ${version} */
const VERSION = ${JSON.stringify(version)};
const CACHE = "lifeos-" + VERSION;
const BASE = new URL("./", self.location).pathname;
const ASSETS = ${JSON.stringify(files)};

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) => cache.addAll(ASSETS.map((a) => BASE + a)))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith("lifeos-") && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

function pageFor(pathname) {
  if (pathname.endsWith("/")) return pathname + "index.html";
  if (!/\\.[a-z0-9]+$/i.test(pathname)) return pathname + "/index.html";
  return pathname;
}

self.addEventListener("fetch", (event) => {
  const request = event.request;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin || !url.pathname.startsWith(BASE)) return;

  // Next's router probes routes with HEAD before prefetching: answer from the cached page.
  if (request.method === "HEAD") {
    event.respondWith(
      caches.match(pageFor(url.pathname)).then((hit) => (hit ? new Response(null, { status: 200, headers: hit.headers }) : fetch(request))),
    );
    return;
  }
  if (request.method !== "GET") return;

  if (request.mode === "navigate") {
    // App shell pages are part of this version: serve them from cache, fall back to the network.
    event.respondWith(
      caches.open(CACHE).then(async (cache) => {
        const hit = (await cache.match(pageFor(url.pathname))) || (await cache.match(request, { ignoreSearch: true }));
        if (hit) return hit;
        try {
          return await fetch(request);
        } catch (error) {
          return (await cache.match(BASE + "vida/index.html")) || Response.error();
        }
      }),
    );
    return;
  }

  event.respondWith(
    caches.match(request, { ignoreSearch: true }).then(
      (hit) =>
        hit ||
        fetch(request).then((response) => {
          if (response.ok && response.type === "basic") {
            const copy = response.clone();
            caches.open(CACHE).then((cache) => cache.put(request, copy));
          }
          return response;
        }),
    ),
  );
});
`;

writeFileSync(path.join(root, "sw.js"), sw);
console.log(`sw.js: ${files.length} archivos precargados · versión ${version}`);
